let currentLang = localStorage.getItem("portfolioLang") || "es";

const langBtn = document.getElementById("langBtn");
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");
const heroPhotoCard = document.getElementById("heroPhotoCard");

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("portfolioLang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const value = translations[lang][key];
    if (value) element.textContent = value;
  });

  langBtn.textContent = lang === "es" ? "EN" : "ES";
  langBtn.setAttribute("aria-label", lang === "es" ? "Cambiar a inglés" : "Switch to Spanish");
}

function toggleMenu() {
  const isOpen = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
}

langBtn.addEventListener("click", () => setLanguage(currentLang === "es" ? "en" : "es"));
menuToggle.addEventListener("click", toggleMenu);

document.querySelectorAll(".nav-links a").forEach((link) => {
  link.addEventListener("click", () => {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});

document.addEventListener("click", (event) => {
  const clickInsideMenu = navLinks.contains(event.target);
  const clickOnToggle = menuToggle.contains(event.target);
  if (!clickInsideMenu && !clickOnToggle) {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  }
});

if (heroPhotoCard) {
  heroPhotoCard.addEventListener("mousemove", (event) => {
    if (window.innerWidth < 1024) return;
    const rect = heroPhotoCard.getBoundingClientRect();
    const x = event.clientX - rect.left;
    const y = event.clientY - rect.top;
    const rotateY = ((x / rect.width) - 0.5) * 8;
    const rotateX = ((y / rect.height) - 0.5) * -8;
    heroPhotoCard.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg)`;
  });

  heroPhotoCard.addEventListener("mouseleave", () => {
    heroPhotoCard.style.transform = "perspective(1000px) rotateX(0deg) rotateY(0deg)";
  });
}

document.getElementById("year").textContent = new Date().getFullYear();

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
setLanguage(currentLang);
